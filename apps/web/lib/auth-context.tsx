"use client";

import React, { createContext, useContext, useEffect, useState, useCallback } from "react";
import { insforge } from "./insforge";
import { UserProfile, Vendor } from "./types";

interface User {
  id: string;
  email: string;
  name?: string;
  [key: string]: any;
}

interface AuthContextType {
  user: User | null;
  profile: UserProfile | null;
  vendor: Vendor | null;
  isLoading: boolean;
  isAdmin: boolean;
  isSeller: boolean;
  isAuthModalOpen: boolean;
  authModalMode: "signin" | "signup";
  openAuthModal: (mode?: "signin" | "signup") => void;
  closeAuthModal: () => void;
  signIn: (email: string, password: string) => Promise<{ success: boolean; error?: string }>;
  signUp: (email: string, password: string, fullName?: string) => Promise<{ success: boolean; error?: string; requireVerification?: boolean }>;
  signInWithGoogle: () => Promise<{ success: boolean; error?: string }>;
  signOut: () => Promise<void>;
  refreshProfile: () => Promise<void>;
}

const AuthContext = createContext<AuthContextType | undefined>(undefined);

export function AuthProvider({ children }: { children: React.ReactNode }) {
  const [user, setUser] = useState<User | null>(null);
  const [profile, setProfile] = useState<UserProfile | null>(null);
  const [vendor, setVendor] = useState<Vendor | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [isAuthModalOpen, setIsAuthModalOpen] = useState(false);
  const [authModalMode, setAuthModalMode] = useState<"signin" | "signup">("signin");

  const openAuthModal = useCallback((mode: "signin" | "signup" = "signin") => {
    setAuthModalMode(mode);
    setIsAuthModalOpen(true);
  }, []);

  const closeAuthModal = useCallback(() => {
    setIsAuthModalOpen(false);
  }, []);

  const fetchVendor = useCallback(async (userId: string) => {
    try {
      const { data, error } = await insforge.database
        .from("vendors")
        .select("*")
        .eq("user_id", userId)
        .maybeSingle();

      if (data && !error) {
        setVendor(data as Vendor);
      } else {
        setVendor(null);
      }
    } catch {
      setVendor(null);
    }
  }, []);

  const fetchProfile = useCallback(async (userId: string, userEmail: string) => {
    try {
      const { data, error } = await insforge.database
        .from("profiles")
        .select("*")
        .eq("id", userId)
        .single();

      if (data && !error) {
        setProfile(data as UserProfile);
      } else {
        // Fallback default customer profile if row not yet generated by trigger
        setProfile({
          id: userId,
          email: userEmail,
          full_name: null,
          avatar_url: null,
          phone: null,
          role: "customer",
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
        });
      }
    } catch (err) {
      console.warn("Could not load user profile:", err);
      setProfile({
        id: userId,
        email: userEmail,
        full_name: null,
        avatar_url: null,
        phone: null,
        role: "customer",
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      });
    }
  }, []);

  const initAuth = useCallback(async () => {
    try {
      setIsLoading(true);
      const { data, error } = await insforge.auth.getCurrentUser();
      if (data?.user && !error) {
        setUser(data.user as User);
        await Promise.all([
          fetchProfile(data.user.id, data.user.email),
          fetchVendor(data.user.id),
        ]);
      } else {
        setUser(null);
        setProfile(null);
        setVendor(null);
      }
    } catch (err) {
      console.warn("Auth initialization error:", err);
      setUser(null);
      setProfile(null);
      setVendor(null);
    } finally {
      setIsLoading(false);
    }
  }, [fetchProfile, fetchVendor]);

  useEffect(() => {
    initAuth();
  }, [initAuth]);

  const signIn = async (email: string, password: string) => {
    try {
      const { data, error } = await insforge.auth.signInWithPassword({
        email: email.trim(),
        password,
      });

      if (error || !data?.user) {
        return {
          success: false,
          error: error?.message || "Invalid email or password",
        };
      }

      setUser(data.user as User);
      await Promise.all([
        fetchProfile(data.user.id, data.user.email),
        fetchVendor(data.user.id),
      ]);
      closeAuthModal();
      return { success: true };
    } catch (err: any) {
      return {
        success: false,
        error: err?.message || "Sign in request failed. Please try again.",
      };
    }
  };

  const signUp = async (email: string, password: string, fullName?: string) => {
    try {
      const { data, error } = await insforge.auth.signUp({
        email: email.trim(),
        password,
        name: fullName?.trim() || undefined,
      });

      if (error) {
        return {
          success: false,
          error: error.message || "Failed to create account",
        };
      }

      if (data?.user) {
        setUser(data.user as User);
        await Promise.all([
          fetchProfile(data.user.id, data.user.email),
          fetchVendor(data.user.id),
        ]);
        closeAuthModal();
        return { success: true };
      }

      // If email verification is required by InsForge settings
      return {
        success: true,
        requireVerification: true,
      };
    } catch (err: any) {
      return {
        success: false,
        error: err?.message || "Registration request failed. Please try again.",
      };
    }
  };

  const signInWithGoogle = async (): Promise<{ success: boolean; error?: string }> => {
    try {
      const redirectTo = typeof window !== "undefined" ? window.location.origin : undefined;
      if (!redirectTo) {
        return { success: false, error: "Redirect URL unavailable." };
      }
      const { error } = await insforge.auth.signInWithOAuth("google", { redirectTo });
      if (error) {
        return { success: false, error: error.message || "Could not start Google sign in." };
      }
      return { success: true };
    } catch (err: any) {
      return { success: false, error: err?.message || "Google sign in failed. Please try again." };
    }
  };

  const signOut = async () => {
    try {
      await insforge.auth.signOut();
    } catch (err) {
      console.warn("Error signing out:", err);
    } finally {
      setUser(null);
      setProfile(null);
      setVendor(null);
    }
  };

  const refreshProfile = async () => {
    if (user) {
      await Promise.all([
        fetchProfile(user.id, user.email),
        fetchVendor(user.id),
      ]);
    }
  };

  // Strict Single Admin check: both UUID and role must match.
  const SINGLE_ADMIN_UUID = "e2f6c2a3-a0e4-46bf-a13f-5b6d088f839d";
  const isAdmin =
    user?.id === SINGLE_ADMIN_UUID && profile?.role === "admin";

  // Seller access check: active vendor record in vendors table, or admin
  const isSeller = Boolean(
    (vendor?.status === "active") || isAdmin
  );

  return (
    <AuthContext.Provider
      value={{
        user,
        profile,
        vendor,
        isLoading,
        isAdmin,
        isSeller,
        isAuthModalOpen,
        authModalMode,
        openAuthModal,
        closeAuthModal,
        signIn,
        signUp,
        signInWithGoogle,
        signOut,
        refreshProfile,
      }}
    >
      {children}
    </AuthContext.Provider>
  );
}

export function useAuth() {
  const context = useContext(AuthContext);
  if (!context) {
    throw new Error("useAuth must be used within an AuthProvider");
  }
  return context;
}

/**
 * Resilient client-side access token retrieval.
 * Tries getValidAccessToken() first, then falls back to refreshSession().
 * Use this before making fetch() calls to API routes.
 */
export async function getClientAccessToken(): Promise<string | null> {
  try {
    const token = await insforge.getHttpClient().getValidAccessToken();
    if (token && token !== "undefined" && token !== "null") return token;
  } catch {
    // ignore and try refresh
  }

  try {
    const { data } = await insforge.auth.refreshSession();
    if (data?.accessToken) return data.accessToken;
  } catch {
    // ignore
  }

  return null;
}
